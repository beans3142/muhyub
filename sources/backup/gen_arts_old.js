// ---------- 대표 무공: 세력마다 최소 15개 ----------
// 고정 이름 전부 + 등급 할당량(삼류 기초 심법·초식 → 절세 비전)에 맞춰 생성 무공에서 고른다
const QUOTA = { 삼류: 3, 이류: 4, 일류: 4, 상승: 3, 절세: 2 };
const SIG = {};
for (const fac of Object.keys(F)) {
  if (fac === 'free') continue;
  const mine = out.filter(o => o.f === fac);
  const sel = mine.filter(o => o.fixed);
  const have = {}; for (const o of sel) have[o.g] = (have[o.g] || 0) + 1;
  const need = Object.assign({}, QUOTA);
  for (const g of Object.keys(need)) need[g] = Math.max(0, need[g] - (have[g] || 0));
  // 심법 하나와 보신경 하나는 꼭 넣는다
  for (const k of ['심법', '보신']) if (!sel.some(o => o.k === k)) { const c = mine.find(o => o.k === k && !o.base && !sel.includes(o)); if (c) { sel.push(c); need[c.g] = Math.max(0, (need[c.g] || 0) - 1); } }
  for (const g of Object.keys(need)) {
    const pool = mine.filter(o => o.g === g && !o.fixed && !o.base && !sel.includes(o));
    const kindsUsed = new Set(sel.map(o => o.k));
    pool.sort((a, b) => (kindsUsed.has(a.k) ? 1 : 0) - (kindsUsed.has(b.k) ? 1 : 0));
    sel.push(...pool.slice(0, need[g]));
  }
  while (sel.length < 15) { const c = mine.find(o => !sel.includes(o) && !o.base); if (!c) break; sel.push(c); }
  const order = ['삼류', '이류', '일류', '상승', '절세'];
  SIG[fac] = sel.sort((a, b) => order.indexOf(a.g) - order.indexOf(b.g)).map(o => [o.n, o.k, o.g, o.tag || '']);
}
const sigCount = Object.values(SIG).map(a => a.length);
