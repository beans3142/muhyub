// 등급: 삼류·이류·일류·절정·절세. prestige별 가중치
const GRADE_W = {
  1: { 삼류: 40, 이류: 32, 일류: 20, 상승: 7, 절세: 1 },
  2: { 삼류: 30, 이류: 30, 일류: 25, 상승: 12, 절세: 3 },
  3: { 삼류: 25, 이류: 28, 일류: 27, 상승: 15, 절세: 5 },
};
const ATTR_OF_ROOT = {};
for (const a of Object.keys(ROOT)) for (const r of ROOT[a]) ATTR_OF_ROOT[r] = a;

const ATTR_CH = { 양: '양화염적홍일열금', 음: '음빙한설월상소현', 독: '독사부골녹흑' };
function attrOf(name, fallback) { for (const k of Object.keys(ATTR_CH)) for (const c of ATTR_CH[k]) if (name.includes(c) && rnd() < 0.5) return k; return fallback; }
function makeName(fac, kind, g) {
  const f = F[fac];
  const suf = pick(KINDS[kind]);
  const own = f.roots.length && rnd() < 0.55 ? pick(f.roots) : null;
  let root;
  if (g === '절세' && rnd() < 0.6) root = pick(TOP2);
  else if (own) root = own.length >= 2 && rnd() < 0.6 ? own : own[0] + sylFor(g);
  else { let x, y, t = 0; do { x = sylFor(g); y = sylFor(g); t++; } while ((x === y || MODERN.has(x + y)) && t < 20); root = x + y; }
  if (suf === '금나수') return { name: root + suf, attr: attrOf(root, f.attr || '중립') };
  const p = rnd();
  let name;
  if (p < 0.62) name = root + suf;                                                   // 남수검법
  else if (p < 0.82) name = root + sylFor(g) + suf;                                  // 청운학검
  else if (p < 0.94 && NUMSUF[kind]) name = pick(NUM) + NUMSUF[kind] + root + suf;   // 이십사수매화검법
  else name = root + sylFor(g) + sylFor(g) + suf;                                    // 4자 어근
  return { name, attr: attrOf(root, f.attr && ['양', '음', '독'].includes(f.attr) ? f.attr : '중립') };
}

const out = [];
const seen = new Set();
function add(o) { if (seen.has(o.n)) return false; seen.add(o.n); out.push(o); return true; }
for (const fac of Object.keys(F)) {
  const f = F[fac];
  for (const [n, k, g] of f.fixed) add({ n, k, g, a: f.attr === '불' || f.attr === '도가' || !f.attr ? '중립' : f.attr, f: fac, m: pick(MYORI), fixed: 1 });
  let made = 0, tries = 0;
  while (made < f.n && tries < f.n * 20) {
    tries++;
    const kind = wpick(f.kinds);
    const g = wpick(GRADE_W[f.prestige]);
    const { name, attr } = makeName(fac, kind, g);
    if (name.length < 2 || name.length > 9) continue;
    if ([...MODERN].some(w => name.startsWith(w) && !(f.roots || []).includes(w))) continue;
    if (add({ n: name, k: kind, g, a: attr, f: fac, m: pick(MYORI) })) made++;
  }
}

// 갈래 무공: 고정 이름에서 어근 한 글자만 바꾼다 (청풍검법 → 청운검법·백풍검법). 등급은 원본 ±1
const GR = ['삼류', '이류', '일류', '상승', '절세'];
const fixedList = out.filter(o => o.fixed && o.n.length <= 7 && !o.n.includes(' '));
for (const o of fixedList) {
  const ks = (KINDS[o.k] || []).slice().sort((x, y) => y.length - x.length);
  const suf = ks.find(x => o.n.endsWith(x)); if (!suf) continue;
  const root = o.n.slice(0, -suf.length); if (root.length < 2) continue;
  const gi = GR.indexOf(o.g);
  for (let i = 0, made = 0; i < 12 && made < 4; i++) {
    const pos = Math.floor(rnd() * root.length);
    const g = GR[Math.max(0, Math.min(4, gi + Math.floor(rnd() * 3) - 1))];
    const nr = root.slice(0, pos) + sylFor(g) + root.slice(pos + 1);
    if (nr === root || MODERN.has(nr.slice(0, 2))) continue;
    if (add({ n: nr + suf, k: o.k, g, a: o.a, f: o.f, m: pick(MYORI), base: o.n })) made++;
  }
}

